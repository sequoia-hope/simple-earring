#!/usr/bin/env python3
"""Circuit Composer's view of the board: compose/earring/.

The earring is script-built, not a composition, so Composer gets what its
other script-built earrings (bolt, flame) give it: circuit.json (every part
with its pins -> nets, from circuit.py + bom/parts.yaml), composed.json (the
minimal parts/nets form `ccomp floorplan` reads) and a board.json saying so.
The KiCad board is found at Composer's default, hw/earring/a/earring.kicad_pcb.

    python3 scripts/export_compose.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from circuit import build_circuit, led_zones, load_design, load_parts  # noqa: E402
from paths import BOARD, ROOT  # noqa: E402

DIR = ROOT / "compose" / BOARD


def main():
    design = load_design()
    c = build_circuit(design)
    parts = load_parts()
    comps = {}
    for ref, comp in sorted(c.components.items()):
        p = parts[comp.part]
        comps[ref] = {"part": comp.part, "value": comp.value,
                      "footprint": comp.footprint or p["footprint"],
                      "lcsc": comp.lcsc or p.get("lcsc", "") or "",
                      "mpn": p.get("mpn") or "", "pins": comp.pins}
    nets = {k: [f"{r}.{p}" for r, p in v] for k, v in sorted(c.nets.items())}
    DIR.mkdir(parents=True, exist_ok=True)
    note = "Generated by scripts/export_compose.py from scripts/circuit.py and bom/parts.yaml; do not edit."
    json.dump({"note": note, "zones": led_zones(design), "components": comps, "nets": nets},
              open(DIR / "circuit.json", "w"), indent=1)
    json.dump({"board": BOARD, "parts": {r: {} for r in comps}, "nets": nets},
              open(DIR / "composed.json", "w"), indent=1)
    json.dump({"note": "Script-built by build.py: the circuit is circuit.json (scripts/circuit.py), "
                       "not a composition. The board is hw/earring/a/earring.kicad_pcb.",
               "composed": "composed.json"},
              open(DIR / "board.json", "w"), indent=1)
    print(json.dumps({"components": len(comps), "nets": len(nets), "dir": str(DIR.relative_to(ROOT))}))


if __name__ == "__main__":
    main()
